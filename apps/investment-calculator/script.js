  function getEffectiveAnnualRate(nominalRatePercent, compoundKey) {
    const nominalRate = nominalRatePercent / 100;
    if (compoundKey === "continuous") {
      return Math.exp(nominalRate) - 1;
    }

    const frequency = compoundFrequencies[compoundKey];
    const base = 1 + nominalRate / frequency.periods;
    if (base <= 0) {
      throw new Error(copy.errors.invalidRateFrequency);
    }

    return Math.pow(base, frequency.periods) - 1;
  }

  function getPeriodRate(annualRatePercent, compoundKey, periodsPerYear) {
    const effectiveAnnualRate = getEffectiveAnnualRate(annualRatePercent, compoundKey);
    const periodBase = 1 + effectiveAnnualRate;
    if (periodBase < 0) {
      throw new Error(copy.errors.invalidEffectiveRate);
    }
    return Math.pow(periodBase, 1 / periodsPerYear) - 1;
  }

  function simulateProjection({
    initialAmount,
    contributionAmount,
    years,
    annualRate,
    contributionFrequency,
    contributionTiming,
    compoundFrequency,
  }) {
    const frequency = contributionFrequencies[contributionFrequency];
    const periodsPerYear = frequency.periods;
    const totalPeriods = Math.max(0, Math.round(years * periodsPerYear));
    const periodRate = getPeriodRate(annualRate, compoundFrequency, periodsPerYear);
    const effectiveAnnualRate = getEffectiveAnnualRate(annualRate, compoundFrequency);

    let balance = initialAmount;
    let periodicContributions = 0;
    const yearRows = [];
    const points = [{ time: 0, value: balance }];
    let yearContribution = 0;
    let yearInterest = 0;

    for (let period = 1; period <= totalPeriods; period += 1) {
      const deposit = contributionAmount;
      let interestForPeriod = 0;

      if (contributionTiming === "beginning" && deposit > 0) {
        balance += deposit;
        periodicContributions += deposit;
        yearContribution += deposit;
      }

      interestForPeriod = balance * periodRate;
      balance += interestForPeriod;
      yearInterest += interestForPeriod;

      if (contributionTiming === "end" && deposit > 0) {
        balance += deposit;
        periodicContributions += deposit;
        yearContribution += deposit;
      }

      const snapshotDue = period % periodsPerYear === 0 || period === totalPeriods;
      if (snapshotDue) {
        const yearsElapsed = period / periodsPerYear;
        yearRows.push({
          label: buildPeriodLabel(period, periodsPerYear),
          contribution: yearContribution,
          interest: yearInterest,
          endingBalance: balance,
          yearsElapsed,
        });
        points.push({ time: yearsElapsed, value: balance });
        yearContribution = 0;
        yearInterest = 0;
      }
    }

    return {
      endingBalance: balance,
      totalInvested: initialAmount + periodicContributions,
      periodicContributions,
      totalInterest: balance - (initialAmount + periodicContributions),
      effectiveAnnualRate,
      periodsPerYear,
      totalPeriods,
      yearRows,
      points,
    };
  }

  function buildPeriodLabel(period, periodsPerYear) {
    if (periodsPerYear === 12) {
      if (period % 12 === 0) {
        return `${copy.periodTokens.year} ${period / 12}`;
      }
      const wholeYears = Math.floor(period / 12);
      const remainingMonths = period % 12;
      if (wholeYears === 0) {
        return `${copy.periodTokens.month} ${remainingMonths}`;
      }
      return `${copy.periodTokens.year} ${wholeYears} + ${remainingMonths}m`;
    }

    if (periodsPerYear === 1) {
      return `${copy.periodTokens.year} ${period}`;
    }

    const yearsElapsed = period / periodsPerYear;
    return `${numberFormatter.format(yearsElapsed)} ${pluralize("year", yearsElapsed)}`;
  }

