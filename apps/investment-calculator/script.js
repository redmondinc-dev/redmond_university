  function solveContribution(inputs) {
    const periodsPerYear = contributionFrequencies[inputs.contributionFrequency].periods;
    const baseline = simulateProjection({ ...inputs, contributionAmount: 0 });
    if (baseline.endingBalance >= inputs.targetAmount) {
      return {
        simulation: baseline,
        solvedValue: 0,
        targetAmount: inputs.targetAmount,
      };
    }

    let low = 0;
    let high = Math.max(100, inputs.targetAmount / Math.max(1, inputs.years * periodsPerYear));
    let projection = simulateProjection({ ...inputs, contributionAmount: high });

    while (projection.endingBalance < inputs.targetAmount && high < 10000000) {
      high *= 2;
      projection = simulateProjection({ ...inputs, contributionAmount: high });
    }

    if (projection.endingBalance < inputs.targetAmount) {
      throw new Error(copy.errors.contributionSearch);
    }

    for (let step = 0; step < 80; step += 1) {
      const midpoint = (low + high) / 2;
      const attempt = simulateProjection({ ...inputs, contributionAmount: midpoint });
      if (attempt.endingBalance >= inputs.targetAmount) {
        high = midpoint;
        projection = attempt;
      } else {
        low = midpoint;
      }
    }

    return {
      simulation: projection,
      solvedValue: high,
      targetAmount: inputs.targetAmount,
    };
  }

  function solveStartingAmount(inputs) {
    const periodsPerYear = contributionFrequencies[inputs.contributionFrequency].periods;
    const baseline = simulateProjection({ ...inputs, initialAmount: 0 });
    if (baseline.endingBalance >= inputs.targetAmount) {
      return {
        simulation: baseline,
        solvedValue: 0,
        targetAmount: inputs.targetAmount,
      };
    }

    let low = 0;
    let high = Math.max(inputs.targetAmount, inputs.contributionAmount * inputs.years * periodsPerYear);
    let projection = simulateProjection({ ...inputs, initialAmount: high });

    while (projection.endingBalance < inputs.targetAmount && high < 1000000000) {
      high *= 2;
      projection = simulateProjection({ ...inputs, initialAmount: high });
    }

    if (projection.endingBalance < inputs.targetAmount) {
      throw new Error(copy.errors.startingAmountSearch);
    }

    for (let step = 0; step < 80; step += 1) {
      const midpoint = (low + high) / 2;
      const attempt = simulateProjection({ ...inputs, initialAmount: midpoint });
      if (attempt.endingBalance >= inputs.targetAmount) {
        high = midpoint;
        projection = attempt;
      } else {
        low = midpoint;
      }
    }

    return {
      simulation: projection,
      solvedValue: high,
      targetAmount: inputs.targetAmount,
    };
  }

  function solveRate(inputs) {
    const lowRate = -99;
    let lowProjection = simulateProjection({ ...inputs, annualRate: lowRate });
    if (lowProjection.endingBalance >= inputs.targetAmount) {
      return {
        simulation: lowProjection,
        solvedValue: lowRate,
        targetAmount: inputs.targetAmount,
      };
    }

    let low = lowRate;
    let high = Math.max(6, inputs.annualRate);
    let highProjection = simulateProjection({ ...inputs, annualRate: high });

    while (highProjection.endingBalance < inputs.targetAmount && high < 1000) {
      high = high < 24 ? high * 2 : high + 20;
      highProjection = simulateProjection({ ...inputs, annualRate: high });
    }

    if (highProjection.endingBalance < inputs.targetAmount) {
      throw new Error(copy.errors.rateOutOfRange);
    }

    let bestProjection = highProjection;
    for (let step = 0; step < 100; step += 1) {
      const midpoint = (low + high) / 2;
      const attempt = simulateProjection({ ...inputs, annualRate: midpoint });
      if (attempt.endingBalance >= inputs.targetAmount) {
        high = midpoint;
        bestProjection = attempt;
      } else {
        low = midpoint;
        lowProjection = attempt;
      }
    }

    return {
      simulation: bestProjection,
      solvedValue: high,
      targetAmount: inputs.targetAmount,
    };
  }

  function solveLength(inputs) {
    if (inputs.initialAmount >= inputs.targetAmount) {
      return {
        simulation: simulateProjection({ ...inputs, years: 0 }),
        solvedValue: 0,
        solvedPeriods: 0,
        targetAmount: inputs.targetAmount,
      };
    }

    const periodsPerYear = contributionFrequencies[inputs.contributionFrequency].periods;
    const periodRate = getPeriodRate(inputs.annualRate, inputs.compoundFrequency, periodsPerYear);
    const maxPeriods = periodsPerYear * 120;
    let balance = inputs.initialAmount;

    for (let period = 1; period <= maxPeriods; period += 1) {
      if (inputs.contributionTiming === "beginning" && inputs.contributionAmount > 0) {
        balance += inputs.contributionAmount;
      }

      balance += balance * periodRate;

      if (inputs.contributionTiming === "end" && inputs.contributionAmount > 0) {
        balance += inputs.contributionAmount;
      }

      if (balance >= inputs.targetAmount) {
        const years = period / periodsPerYear;
        return {
          simulation: simulateProjection({ ...inputs, years }),
          solvedValue: years,
          solvedPeriods: period,
          targetAmount: inputs.targetAmount,
        };
      }
    }

    throw new Error(copy.errors.lengthOutOfRange);
  }

  function formatDuration(totalPeriods, periodsPerYear) {
    if (totalPeriods === 0) {
      return `0 ${pluralize("year", 0)}`;
    }

    if (periodsPerYear === 12) {
      const years = Math.floor(totalPeriods / 12);
      const months = totalPeriods % 12;
      if (years === 0) {
        return `${months} ${pluralize("month", months)}`;
      }
      if (months === 0) {
        return `${years} ${pluralize("year", years)}`;
      }
      return `${years} ${pluralize("year", years)} ${copy.words.and} ${months} ${pluralize("month", months)}`;
    }

    if (periodsPerYear === 1) {
      return `${totalPeriods} ${pluralize("year", totalPeriods)}`;
    }

    const years = totalPeriods / periodsPerYear;
    return `${numberFormatter.format(years)} ${pluralize("year", years)}`;
  }

