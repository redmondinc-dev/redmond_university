  let currentTooltipMode = "endBalance";
  const tooltip = document.getElementById("formulaTooltip");
  const tooltipTitle = document.getElementById("formulaTooltipTitle");
  const tooltipFormula = document.getElementById("formulaTooltipFormula");
  const tooltipVars = document.getElementById("formulaTooltipVars");
